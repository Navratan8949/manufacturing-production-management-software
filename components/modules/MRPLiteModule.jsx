"use client";

import React, { useState, useMemo } from "react";
import { useApp } from "@/context/AppContext";
import {
  Calculator,
  ShoppingCart,
  AlertTriangle,
  CheckCircle2,
  ArrowRight,
  TrendingDown,
  Info,
} from "lucide-react";
import { formatINR } from "@/lib/utils";

export function MRPLiteModule() {
  const { data, createPurchaseOrder, setActiveView } = useApp();
  const [selectedWOs, setSelectedWOs] = useState(
    data.workOrders.filter((w) => w.status === "Planned" || w.status === "Material Reserved").map((w) => w.id)
  );

  const toggleWOCheck = (woId) => {
    setSelectedWOs((prev) =>
      prev.includes(woId) ? prev.filter((id) => id !== woId) : [...prev, woId]
    );
  };

  // Perform MRP Deterministic Calculations
  const mrpCalculations = useMemo(() => {
    const activePlannedWOs = (data.workOrders || []).filter((w) => selectedWOs.includes(w.id));
    const grossMap = {};

    activePlannedWOs.forEach((wo) => {
      const bom = data.boms.find((b) => b.id === wo.bomId || b.productCode === wo.productCode);
      if (bom) {
        const scrapFactor = 1 + (bom.scrapAllowancePercent || 0) / 100;
        (bom.items || []).forEach((item) => {
          const req = item.qty * wo.plannedQuantity * scrapFactor;
          if (!grossMap[item.materialCode]) {
            grossMap[item.materialCode] = {
              code: item.materialCode,
              name: item.name,
              unit: item.unit,
              grossReq: 0,
            };
          }
          grossMap[item.materialCode].grossReq += req;
        });
      }
    });

    const lines = Object.values(grossMap).map((req) => {
      const mat = data.rawMaterials.find((m) => m.code === req.code);
      const onHand = mat ? mat.currentStock : 0;
      const reserved = mat ? mat.reservedStock : 0;
      const eligibleAvailable = Math.max(0, onHand - reserved);

      // Incoming from submitted POs
      let incomingPOQty = 0;
      (data.purchaseOrders || []).forEach((po) => {
        if (po.status === "Submitted" || po.status === "Partially Received") {
          (po.items || []).forEach((poi) => {
            if (poi.materialCode === req.code) {
              incomingPOQty += (poi.orderedQty - (poi.receivedQty || 0));
            }
          });
        }
      });

      // Net shortage formula: max(0, Gross requirement - Eligible available stock)
      const grossReq = Number(req.grossReq.toFixed(1));
      const netShortage = Math.max(0, Number((grossReq - eligibleAvailable).toFixed(1)));
      const suggestedPO = Math.max(0, Number((netShortage - incomingPOQty).toFixed(1)));

      return {
        code: req.code,
        name: req.name,
        unit: req.unit,
        grossReq,
        eligibleAvailable,
        onHand,
        reserved,
        incomingPOQty,
        netShortage,
        suggestedPO,
        unitCost: mat?.unitCost || 500,
        supplierId: mat?.preferredSupplierId || data.suppliers[0]?.id,
        supplierName: data.suppliers.find((s) => s.id === mat?.preferredSupplierId)?.name || data.suppliers[0]?.name,
      };
    });

    return lines;
  }, [data.workOrders, data.boms, data.rawMaterials, data.purchaseOrders, data.suppliers, selectedWOs]);

  const totalSuggestedPOValue = mrpCalculations.reduce(
    (sum, line) => sum + line.suggestedPO * line.unitCost,
    0
  );

  const handleGeneratePOFromShortages = () => {
    const shortagesToOrder = mrpCalculations.filter((l) => l.suggestedPO > 0);
    if (shortagesToOrder.length === 0) return;

    // Group by supplier
    const supplierGroups = {};
    shortagesToOrder.forEach((item) => {
      const supId = item.supplierId;
      if (!supplierGroups[supId]) {
        supplierGroups[supId] = {
          supplierId: supId,
          supplierName: item.supplierName,
          items: [],
        };
      }
      supplierGroups[supId].items.push({
        materialCode: item.code,
        name: item.name,
        orderedQty: Math.ceil(item.suggestedPO),
        unitPrice: item.unitCost,
        total: Math.ceil(item.suggestedPO) * item.unitCost,
        unit: item.unit,
      });
    });

    Object.values(supplierGroups).forEach((group) => {
      const totalAmount = group.items.reduce((sum, i) => sum + i.total, 0);
      createPurchaseOrder({
        supplierId: group.supplierId,
        supplierName: group.supplierName,
        expectedDeliveryDate: new Date(Date.now() + 5 * 86400000).toISOString().slice(0, 10),
        totalAmount,
        items: group.items,
        notes: "Automated replenishment generated by MRP Lite calculation engine.",
      });
    });

    setActiveView("purchase-orders");
  };

  return (
    <div className="space-y-6">
      {/* Header and Actions */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 p-5 rounded-xl bg-white border border-slate-200 shadow-2xs">
        <div>
          <h2 className="text-lg font-bold text-slate-900 tracking-tight">Material Requirements Planning (MRP Lite)</h2>
          <p className="text-xs text-slate-500 mt-0.5">
            Formula: Net Shortage = max(0, Gross Requirement − Eligible Available Stock). Prevents mid-run assembly stalls.
          </p>
        </div>

        <button
          onClick={handleGeneratePOFromShortages}
          disabled={totalSuggestedPOValue === 0}
          className="px-4 py-2 text-xs font-semibold text-white bg-slate-900 hover:bg-slate-800 disabled:opacity-40 rounded-lg flex items-center gap-2 shadow-2xs transition-colors self-start sm:self-auto"
        >
          <ShoppingCart className="w-4 h-4 text-amber-400" />
          <span>Auto-Draft POs for Shortages ({formatINR(totalSuggestedPOValue)})</span>
        </button>
      </div>

      {/* Target Work Orders Selector Strip */}
      <div className="p-4 rounded-xl bg-white border border-slate-200 shadow-2xs space-y-3 text-xs">
        <div className="flex items-center justify-between">
          <span className="font-bold text-slate-900">Include Planned Batches in MRP Run:</span>
          <span className="text-[11px] text-slate-500 font-medium">
            {selectedWOs.length} of {data.workOrders.length} work orders selected
          </span>
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-4 gap-2">
          {data.workOrders.map((wo) => {
            const isChecked = selectedWOs.includes(wo.id);
            return (
              <label
                key={wo.id}
                className={`p-3 rounded-lg border flex items-center gap-3 cursor-pointer transition-colors ${
                  isChecked ? "bg-amber-50/60 border-amber-300" : "bg-slate-50 border-slate-200 hover:bg-slate-100"
                }`}
              >
                <input
                  type="checkbox"
                  checked={isChecked}
                  onChange={() => toggleWOCheck(wo.id)}
                  className="rounded text-amber-500 focus:ring-amber-400"
                />
                <div className="truncate">
                  <p className="font-mono font-bold text-slate-900 text-xs">{wo.workOrderNumber}</p>
                  <p className="text-slate-600 truncate text-[11px]">{wo.productName}</p>
                  <span className="text-[10px] text-slate-500">{wo.plannedQuantity} pcs · {wo.status}</span>
                </div>
              </label>
            );
          })}
        </div>
      </div>

      {/* MRP Calculation Table */}
      <div className="rounded-xl bg-white border border-slate-200 shadow-2xs overflow-hidden">
        <div className="p-4 bg-slate-50 border-b border-slate-200 flex items-center justify-between text-xs">
          <div>
            <h3 className="font-bold text-slate-900">Computed Component Requirements</h3>
            <p className="text-[11px] text-slate-500">
              Aggregated across selected work orders with BOM version scrap allowances
            </p>
          </div>
        </div>

        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs border-collapse">
            <thead className="bg-slate-100 text-slate-600 font-semibold uppercase tracking-wider text-[11px]">
              <tr>
                <th className="p-4">Material Code</th>
                <th className="p-4">Component Material</th>
                <th className="p-4 text-right">Gross Req</th>
                <th className="p-4 text-right">Eligible Avail.</th>
                <th className="p-4 text-right">On-Hand Stock</th>
                <th className="p-4 text-right">Reserved</th>
                <th className="p-4 text-right">Incoming (PO)</th>
                <th className="p-4 text-right">Net Shortage</th>
                <th className="p-4 text-right">Suggested Purchase</th>
                <th className="p-4">Supplier</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {mrpCalculations.map((line, idx) => {
                const hasShortage = line.suggestedPO > 0;
                return (
                  <tr key={idx} className={hasShortage ? "bg-rose-50/40" : "hover:bg-slate-50/50"}>
                    <td className="p-4 font-mono font-bold text-slate-900">{line.code}</td>
                    <td className="p-4 font-semibold text-slate-900">{line.name}</td>
                    <td className="p-4 text-right font-mono font-bold text-slate-900">
                      {line.grossReq} {line.unit}
                    </td>
                    <td className="p-4 text-right font-mono text-slate-700">
                      {line.eligibleAvailable} {line.unit}
                    </td>
                    <td className="p-4 text-right font-mono text-slate-500">
                      {line.onHand} {line.unit}
                    </td>
                    <td className="p-4 text-right font-mono text-amber-600 font-semibold">
                      {line.reserved} {line.unit}
                    </td>
                    <td className="p-4 text-right font-mono text-blue-600 font-semibold">
                      {line.incomingPOQty} {line.unit}
                    </td>
                    <td className="p-4 text-right font-mono font-bold text-rose-600">
                      {line.netShortage} {line.unit}
                    </td>
                    <td className="p-4 text-right font-mono font-bold text-slate-950">
                      {line.suggestedPO > 0 ? (
                        <span className="text-amber-800 bg-amber-100 px-2 py-0.5 rounded font-mono font-bold">
                          {line.suggestedPO} {line.unit}
                        </span>
                      ) : (
                        <span className="text-emerald-700 font-semibold">Covered</span>
                      )}
                    </td>
                    <td className="p-4 text-slate-600 truncate max-w-xs">{line.supplierName}</td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
